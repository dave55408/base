/* Bake the reference-processing pipeline once, outside the simulation. */
const fs=require('node:fs'),path=require('node:path');
const {chromium}=require(require.resolve('playwright',{paths:[__dirname,path.resolve(__dirname,'../elf-adventure')]}));
const {createServer}=require('./server.cjs');
(async()=>{
 const server=createServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));let browser;
 try{
  browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const page=await browser.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));const origin='http://127.0.0.1:'+server.address().port;
  await page.goto(origin+'/project-notes.html');
  for(const file of ['vendor/alpine-three.js','hangar-door-frame.js','assets/reference/enterprise-model-sheet.js','texture-build/original-source.js','assets/reference/image-1444/enterprise-orthos.js','assets/reference/image-1444/lettering-stencils.js','enterprise-reference-lettering.js','enterprise-engineering-shape.js','enterprise-movie-markings.js','enterprise-movie-orthos.js','enterprise-movie-vector-details.js','texture-build/movie-source.js'])await page.addScriptTag({url:origin+'/'+file});
  await page.addScriptTag({url:origin+'/texture-build/third-source.js'});
  if(errors.length)throw Error(errors.join('\n'));
  const onlyThird=process.argv.includes('--third-only');
  const manifest=onlyThird?JSON.parse(fs.readFileSync(path.join(__dirname,'ship-texture-manifest.js'),'utf8').split('window.SHIP_TEXTURE_MANIFEST=')[1].trim().replace(/;$/,'')):{};
  for(const model of onlyThird?['third']:['original','movie','third']){
   const baked=await page.evaluate(async model=>{
    const maps=model==='third'?await createThirdEnterpriseDetailing(AlpineThree):model==='movie'?createMovieEnterpriseDetailing(AlpineThree):createEnterpriseDetailing(AlpineThree);await maps.ready;
    const textures={},metadata={};
    for(const [name,value]of Object.entries(maps)){
     if(value?.isTexture){
      const image=value.image,variants={};
      for(const quality of ['high','low']){
       // Preserve narrow registry/pennant strips; halve hull and glow dimensions.
       const scale=quality==='low'&&image.height>256?.5:1;
       const c=document.createElement('canvas');c.width=Math.round(image.width*scale);c.height=Math.round(image.height*scale);
       c.getContext('2d').drawImage(image,0,0,c.width,c.height);
       variants[quality]={width:c.width,height:c.height,png:c.toDataURL('image/png').split(',')[1]};
      }
      textures[name]=variants;
     }else if(!['ready','referenceWindowLayers'].includes(name))metadata[name]=value;
    }
    return {textures,metadata};
   },model);
   manifest[model]={textures:{},metadata:baked.metadata};
   const bundles={high:{},low:{}};
   for(const [name,variants]of Object.entries(baked.textures)){
    manifest[model].textures[name]={};
    for(const [quality,{width,height,png}]of Object.entries(variants)){
     const file=`assets/textures/ships/${model}/${quality}/${name}.png`;
     fs.mkdirSync(path.dirname(path.join(__dirname,file)),{recursive:true});fs.writeFileSync(path.join(__dirname,file),Buffer.from(png,'base64'));
     manifest[model].textures[name][quality]={width,height,url:file};
     bundles[quality][name]='data:image/png;base64,'+png;
    }
   }
   for(const [quality,images]of Object.entries(bundles))fs.writeFileSync(path.join(__dirname,`assets/textures/ships/${model}/${quality}/bundle.js`),'ShipTextures.receiveBundle('+JSON.stringify(model+'/'+quality)+','+JSON.stringify(images)+');\n');
  }
  fs.writeFileSync(path.join(__dirname,'ship-texture-manifest.js'),'/* Generated by npm run build:textures. */\nwindow.SHIP_TEXTURE_MANIFEST='+JSON.stringify(manifest)+';\n');
  console.log('Baked ship textures in high and low memory sizes.');
 }finally{await browser?.close();await new Promise(r=>server.close(r));}
})().catch(e=>{console.error(e);process.exitCode=1;});
