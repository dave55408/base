// Direct file:// pages have opaque origins. Inline local artwork so generated
// canvases remain origin-clean without relaxing browser security settings.
const fs=require('node:fs');
const path=require('node:path');
const assets={};
for(const name of fs.readdirSync(path.join(__dirname,'assets')).filter(name=>name.endsWith('.png')).sort()){
  assets['assets/'+name]='data:image/png;base64,'+fs.readFileSync(path.join(__dirname,'assets',name)).toString('base64');
}
fs.writeFileSync(path.join(__dirname,'file-assets.js'),'// Generated by npm run build:local-assets. Used only on file:// pages.\nwindow.ELF_LOCAL_ASSETS='+JSON.stringify(assets)+';\n');
console.log('Prepared '+Object.keys(assets).length+' local images.');
